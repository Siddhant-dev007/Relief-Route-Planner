"""Generates data/scenario_stress.csv (large-data stress scenario).

Deterministic: the fixed seed always produces the same file.
Run from the project folder:  py tools/generate_stress.py
"""

import random

SEED = 42
NODES = 60
SHELTERS = 40
PACKAGES_PER_SHELTER = (6, 14)
VEHICLES = 25
EXTRA_ROADS = 90

TYPES = [
    "Food", "Water", "Medicine", "Blankets", "Hygiene kit",
    "Tents", "Baby food", "First aid", "Oxygen", "Clothing",
]
WEIGHTS = {
    "Food": 20, "Water": 25, "Medicine": 8, "Blankets": 15,
    "Hygiene kit": 10, "Tents": 30, "Baby food": 12, "First aid": 6,
    "Oxygen": 18, "Clothing": 14,
}


def main():
    rng = random.Random(SEED)
    lines = [
        "# Scenario 3 - Large-data stress",
        f"# Generated by tools/generate_stress.py (seed {SEED}).",
        f"# {SHELTERS} shelters, {VEHICLES} vehicles, {NODES} nodes.",
        "NAME,Large-Data Stress Scenario",
        f"NODES,{NODES}",
        "DEPOT,0",
        "",
        "[SHELTERS]",
        "id,name,population,urgency,node",
    ]

    shelter_nodes = rng.sample(range(1, NODES), SHELTERS)
    for i, node in enumerate(shelter_nodes, start=1):
        lines.append(
            f"{i},Shelter {i:02d},{rng.randint(50, 2000)},"
            f"{rng.randint(1, 10)},{node}"
        )

    lines += ["", "[PACKAGES]", "id,type,weight,severity,shelterId"]
    package_id = 1
    for shelter in range(1, SHELTERS + 1):
        for _ in range(rng.randint(*PACKAGES_PER_SHELTER)):
            kind = rng.choice(TYPES)
            weight = WEIGHTS[kind] + rng.randint(-3, 3)
            lines.append(
                f"{package_id},{kind},{weight},{rng.randint(1, 10)},{shelter}"
            )
            package_id += 1

    lines += ["", "[VEHICLES]", "id,capacity,available"]
    for v in range(1, VEHICLES + 1):
        available = 0 if rng.random() < 0.1 else 1
        lines.append(f"{v},{rng.choice([60, 80, 100, 120, 150])},{available}")

    # A random spanning tree keeps the network connected,
    # then extra roads add alternative routes.
    lines += ["", "[ROADS]", "from,to,distance"]
    roads = set()
    order = list(range(NODES))
    rng.shuffle(order)
    for k in range(1, NODES):
        a, b = order[k], order[rng.randrange(k)]
        roads.add((min(a, b), max(a, b)))
    while len(roads) < NODES - 1 + EXTRA_ROADS:
        a, b = rng.sample(range(NODES), 2)
        roads.add((min(a, b), max(a, b)))
    for a, b in sorted(roads):
        lines.append(f"{a},{b},{rng.randint(2, 40)}")

    with open("data/scenario_stress.csv", "w", newline="\n") as out:
        out.write("\n".join(lines) + "\n")

    print(f"Wrote {package_id - 1} packages and {len(roads)} roads.")


if __name__ == "__main__":
    main()
